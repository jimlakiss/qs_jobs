"""Exercise the actual isolated capture worker, including Apple's local OCR."""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

ROOT = Path(__file__).resolve().parent
APP = ROOT / 'target/iQs Drawing Viewer.app/Contents/MacOS/iQsDrawingViewer'

def field(id, scope, page=0, bounds=(0.08, 0.06, 0.5, 0.14), turns=0):
    return dict(id=id, name=id, scope=scope, region=dict(page=page, bounds=bounds, turns=turns), overrides={})

def run(path, pages, fields, force=False, fingerprint=None, targets=None):
    task = dict(path=str(path), fingerprint=fingerprint or hashlib.sha256(path.read_bytes()).hexdigest(), pages=pages, fields=fields, force_ocr=force, targets=targets or [])
    proc = subprocess.run([str(APP), '--capture-worker'], input=json.dumps(task), text=True, capture_output=True, timeout=120)
    assert proc.returncode == 0, proc.stderr
    replies = [json.loads(line) for line in proc.stdout.splitlines()]
    assert replies[-1] == 'Done', replies
    return [r['Cell'] for r in replies[:-1]]

def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--source", type=Path)
    args = parser.parse_args()
    vector = ROOT / 'fixtures/vector.pdf'
    cells = run(vector, 1, [field('sheet_id', 'EveryPage')])
    assert cells[0]['value']['text'] == 'iQs synthetic drawing - A101', cells
    assert cells[0]['value']['method'] == 'PDF text', cells
    ocr = run(vector, 1, [field('sheet_id', 'EveryPage')], force=True)
    assert 'A101' in ocr[0]['value']['text'], ocr
    assert ocr[0]['value']['method'] == 'Local OCR', ocr
    # A real image-only PDF, generated by rendering the vector fixture into a scan.
    from PIL import Image
    from pypdf import PdfReader, PdfWriter
    doc_id = hashlib.sha256(vector.read_bytes()).hexdigest()
    request = dict(seq=1, key=dict(doc=doc_id, page=0, level=-1, col=0, row=0))
    proc = subprocess.run([str(APP), '--pdf-worker', str(vector)], input=json.dumps(request).encode()+b'\n', capture_output=True, timeout=30)
    header, pixels = proc.stdout.split(b'\n', 1)
    header = json.loads(header)
    image = Image.frombytes('RGBA', tuple(header['size']), pixels).convert('RGB')
    scan_path = ROOT / 'results/capture_scan.pdf'
    scan_path.parent.mkdir(exist_ok=True)
    image.save(scan_path, resolution=51.2)
    raster = run(scan_path, 1, [field('sheet_id', 'EveryPage')])
    assert 'A101' in raster[0]['value']['text'], raster
    assert raster[0]['value']['method'] == 'Local OCR', raster
    # Select Text uses a transient forced-OCR Once region, independent of field capture.
    selection = run(scan_path, 1, [field('description', 'Once')], force=True)
    assert len(selection) == 1 and selection[0]['page'] == -1, selection
    assert 'A101' in selection[0]['value']['text'] and selection[0]['value']['method'] == 'Local OCR', selection
    # Once can use any source page. Every-page templates have independent overrides.
    template = field('sheet_id', 'EveryPage')
    template['overrides']['1'] = dict(page=1, bounds=[0.7, 0.7, 0.9, 0.9], turns=0)
    # Use a three-page subset to avoid 100 native OCR calls on the empty override.
    multi = PdfWriter()
    source = PdfReader(vector)
    for _ in range(3): multi.add_page(source.pages[0])
    multi_path = ROOT / 'results/capture_multi.pdf'
    with multi_path.open('wb') as output: multi.write(output)
    repeat = run(multi_path, 3, [field('prepared_by', 'Once', page=2), template])
    once = [c for c in repeat if c['field'] == 'prepared_by']
    each = [c for c in repeat if c['field'] == 'sheet_id']
    assert len(once) == 1 and once[0]['page'] == -1 and 'A101' in once[0]['value']['text'], repeat
    assert len(each) == 3 and [c['page'] for c in each] == [0, 1, 2], repeat
    assert each[1]['value']['text'] == '' and each[1]['value']['method'] == 'Local OCR', repeat
    assert 'A101' in each[0]['value']['text'] and 'A101' in each[2]['value']['text'], repeat
    # Cropped/rotated/UserUnit source and a further view rotation.
    rotated = run(ROOT / 'fixtures/rotated_crop.pdf', 1, [field('sheet_id', 'EveryPage', bounds=(0,0,1,1))])
    assert 'A101' in rotated[0]['value']['text'], rotated
    rot_ocr = run(ROOT / 'fixtures/rotated_crop.pdf', 1, [field('sheet_id', 'EveryPage', bounds=(0,0,1,1), turns=3)], force=True)
    assert 'A101' in rot_ocr[0]['value']['text'], rot_ocr
    # Only explicitly selected sibling PDFs are included in the drawing set.
    from generate_fixtures import pdf
    # Old PDF labels hidden by a white revision patch must never leak into CSV.
    revised = ROOT / 'results/capture_hidden_revision.pdf'
    revised.write_bytes(pdf(b'BT /F1 18 Tf 72 650 Td (GROUND FLOOR PLAN) Tj ET '
        b'BT /F1 18 Tf 72 590 Td (27/03/2026) Tj ET '
        b'1 1 1 rg 65 635 400 40 re f 65 575 400 40 re f 0 0 0 rg '
        b'BT /F1 18 Tf 72 650 Td (BASEMENT FLOOR PLAN) Tj ET '
        b'BT /F1 18 Tf 72 590 Td (14/04/2026) Tj ET'))
    revision = run(revised,1,[field('description','EveryPage',bounds=(0.08,0.06,0.7,0.14)),
        field('date','EveryPage',bounds=(0.08,0.14,0.5,0.20))])
    assert revision[0]['value']['text']=='BASEMENT FLOOR PLAN', revision
    assert revision[1]['value']['text']=='14/04/2026', revision
    assert all(c['value']['method']=='Local OCR' for c in revision), revision
    set_dir = ROOT / 'results/capture_set'
    set_dir.mkdir(exist_ok=True)
    for name, number in [('first','A101'),('second','A102'),('excluded','A999')]:
        (set_dir / f'{name}.pdf').write_bytes(pdf(f'BT /F1 18 Tf 72 650 Td (iQs synthetic drawing - {number}) Tj ET'.encode()))
    first, second = set_dir / 'first.pdf', set_dir / 'second.pdf'
    selected = run(first, 1, [field('sheet_id','EveryPage')], targets=[str(first),str(second)])
    assert len(selected) == 2, selected
    assert {c['path'] for c in selected} == {str(first),str(second)}, selected
    assert {c['value']['text'] for c in selected} == {'iQs synthetic drawing - A101','iQs synthetic drawing - A102'}, selected
    # A deletion/extra region on one source must never leak onto a sibling.
    excluded = field('sheet_id','EveryPage')
    excluded['excluded'] = [0]
    inherited = run(first,1,[excluded],targets=[str(first),str(second)])
    assert len(inherited)==1 and inherited[0]['path']==str(second) and 'A102' in inherited[0]['value']['text'], inherited
    multiple = field('sheet_id','EveryPage')
    multiple['page_regions'] = {'0':[multiple['region'],multiple['region']]}
    parts = run(first,1,[multiple])
    assert parts[0]['value']['text'].count('A101')==2, parts
    # Start on the second PDF: Once fields must still be read from their master.
    once = field('prepared_by','Once')
    once['master_doc'] = hashlib.sha256(first.read_bytes()).hexdigest()
    shared = run(second,1,[once,field('sheet_id','EveryPage')],targets=[str(first),str(second)])
    authors = [c for c in shared if c['field']=='prepared_by']
    assert len(authors)==2 and all('A101' in c['value']['text'] for c in authors), shared
    # Changed source identity must fail rather than attaching results to an old PDF.
    bad_task = dict(path=str(vector), fingerprint='0'*64, pages=1, fields=[field('sheet_id','EveryPage')], force_ocr=False)
    bad = subprocess.run([str(APP), '--capture-worker'], input=json.dumps(bad_task), text=True, capture_output=True, timeout=30)
    assert 'PDF changed since opening' in bad.stdout, bad.stdout
    if args.source:
        count = len(PdfReader(args.source).pages)
        source_fields = [field('sheet_id', 'Once', bounds=(0,0,1,1))]
        actual_text = run(args.source, count, source_fields)
        actual_ocr = run(args.source, count, source_fields, force=True)
        assert actual_text[0]['value']['error'] is None and actual_text[0]['value']['text'], actual_text[0]['value']['error']
        assert actual_ocr[0]['value']['error'] is None and actual_ocr[0]['value']['text'], actual_ocr[0]['value']['error']
        print(json.dumps(dict(real_source_pages=count, embedded_characters=len(actual_text[0]['value']['text']), ocr_characters=len(actual_ocr[0]['value']['text']))))
    print(json.dumps(dict(success=True, embedded=cells, forced_ocr=ocr, image_only=raster, repeated=repeat, rotated_ocr=rot_ocr), indent=2))

if __name__ == '__main__': main()
