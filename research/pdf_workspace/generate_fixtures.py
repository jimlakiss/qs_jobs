"""Deterministic, synthetic PDFs for local research; no customer drawings."""
import hashlib
import json
from pathlib import Path
import zlib

ROOT = Path(__file__).resolve().parent / "fixtures"


def pdf(content, *, pages=1, page_options=b"", image=None):
    objects = [b"<< /Type /Catalog /Pages 2 0 R >>", b""]
    objects.append(b"<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>")
    objects.append(b"<< /Length " + str(len(content)).encode() + b" >>\nstream\n" + content + b"\nendstream")
    image_ref = b""
    if image:
        data = zlib.compress(image)
        objects.append(b"<< /Type /XObject /Subtype /Image /Width 64 /Height 64 /ColorSpace /DeviceGray /BitsPerComponent 8 /Filter /FlateDecode /Length " + str(len(data)).encode() + b" >>\nstream\n" + data + b"\nendstream")
        image_ref = b" /XObject << /Im0 5 0 R >>"
    kids = []
    for _ in range(pages):
        kids.append(f"{len(objects)+1} 0 R".encode())
        objects.append(b"<< /Type /Page /Parent 2 0 R /MediaBox [0 0 720 720] /Resources << /Font << /F1 3 0 R >>" + image_ref + b" >> /Contents 4 0 R " + page_options + b" >>")
    objects[1] = b"<< /Type /Pages /Count " + str(pages).encode() + b" /Kids [" + b" ".join(kids) + b"] >>"
    out = bytearray(b"%PDF-1.7\n%\xe2\xe3\xcf\xd3\n")
    offsets = [0]
    for index, obj in enumerate(objects, 1):
        offsets.append(len(out))
        out.extend(f"{index} 0 obj\n".encode() + obj + b"\nendobj\n")
    xref = len(out)
    out.extend(f"xref\n0 {len(objects)+1}\n0000000000 65535 f \n".encode())
    for offset in offsets[1:]:
        out.extend(f"{offset:010d} 00000 n \n".encode())
    out.extend(f"trailer\n<< /Size {len(objects)+1} /Root 1 0 R >>\nstartxref\n{xref}\n%%EOF\n".encode())
    return bytes(out)


def main():
    ROOT.mkdir(exist_ok=True)
    vector = b"0.5 w 72 72 288 144 re S\nBT /F1 18 Tf 72 650 Td (iQs synthetic drawing - A101) Tj ET\n"
    dense = vector + b"\n".join(f"{i % 650+35} 35 m {i % 650+35} 685 l S {35} {i % 650+35} m 685 {i % 650+35} l S".encode() for i in range(10000))
    fixtures = [
        ("vector.pdf", pdf(vector), "vector rectangle: 288 x 144 PDF points; 1:100 gives 10.16 x 5.08 m", "opens"),
        ("dense.pdf", pdf(dense), "20,000 line strokes, repeated dense geometry", "opens"),
        ("rotated_crop.pdf", pdf(vector, page_options=b"/CropBox [36 36 684 684] /Rotate 90 /UserUnit 2"), "nonzero crop origin, rotation, UserUnit=2; transform probe", "opens"),
        ("multipage.pdf", pdf(vector, pages=100), "100 synthetic pages sharing the same content stream; not a real large set", "opens"),
        ("raster.pdf", pdf(b"q 576 0 0 576 72 72 cm /Im0 Do Q", image=bytes((x*7+y*11) % 256 for y in range(64) for x in range(64))), "synthetic grayscale raster only; no text/path snapping expected", "opens"),
        ("malformed.pdf", b"%PDF-1.7\nnot a valid document\n", "intentionally invalid PDF", "error"),
    ]
    manifest = []
    for name, data, purpose, expected in fixtures:
        (ROOT / name).write_bytes(data)
        manifest.append(dict(file=name, sha256=hashlib.sha256(data).hexdigest(), bytes=len(data), purpose=purpose, expected=expected, provenance="Original iQs synthetic fixture generated by generate_fixtures.py"))
    (ROOT / "manifest.json").write_text(json.dumps(manifest, indent=2) + "\n")
    print(f"Generated {len(manifest)} synthetic fixtures")


if __name__ == "__main__":
    main()
